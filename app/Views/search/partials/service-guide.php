    <section aria-labelledby="service-features-heading">
        <h2 id="service-features-heading">Travel Compassでできること</h2>
        <p>航空券・ホテルの候補や予約サイトへのリンクをまとめて確認し、フェリーの航路も探せます。旅の移動手段と宿泊先を検討するときにご利用ください。</p>
        <ul>
            <li><strong>航空券：</strong>都市名やIATAコードから出発地・目的地を選び、片道・往復の日程と人数で検索できます。</li>
            <li><strong>ホテル：</strong>滞在先・宿泊日・人数を指定し、国内・韓国・その他海外のホテル候補を確認できます。</li>
            <li><strong>フェリー：</strong>フェリー会社と航路を選ぶほか、地図から港を選んで航路を探せます。</li>
        </ul>
    </section>
    <section aria-labelledby="service-usage-heading">
        <h2 id="service-usage-heading">使い方</h2>
        <ol>
            <li>検索フォームで「航空券」「ホテル」「フェリー」から探したいものを選びます。</li>
            <li>行き先や日程・人数、または港・航路などの条件を指定して検索します。</li>
            <li>候補を確認し、予約サイトやフェリー会社の公式サイトへ進んで詳細を確認します。予約手続きは遷移先で行います。</li>
        </ol>
        <p>航空券とホテルは「最近の検索」から条件を再入力できます。フェリーは検索履歴の対象外です。</p>
    </section>
    <section aria-labelledby="service-information-heading">
        <h2 id="service-information-heading">情報の取得・更新方針</h2>
        <p>航空券・ホテルの候補情報には外部サービスのAPIを利用しています。取得済みの情報を一時保存して表示する場合があるため、料金や空席・空室状況は閲覧時点の情報と異なることがあります。最終的な料金、空席・空室、予約条件は遷移先の予約サイトでご確認ください。</p>
        <p>フェリーの運賃・ダイヤ・運航状況は参考情報です。最新情報・空席状況は各フェリー会社公式サイトでご確認ください。</p>
    </section>
</div>
